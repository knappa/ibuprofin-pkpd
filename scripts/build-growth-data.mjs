// Generate src/growth-data.js (median weight for age) from the growth-chart
// CSV files in data/growth/. Run with: node scripts/build-growth-data.mjs

import { readFileSync, writeFileSync } from "node:fs";

function readCsv(path) {
  const [header, ...rows] = readFileSync(path, "utf8").trim().split("\n");
  const columns = header.split(",");
  return rows.map((row) => Object.fromEntries(row.split(",").map((value, idx) => [columns[idx], value])));
}

// WHO 0-24 months: column "Month", median column "M".
const whoRows = (sexLabel) =>
  readCsv(`data/growth/who-weight-for-age-0-24mo-${sexLabel}.csv`).map((row) => [Number(row.Month), Number(row.M)]);

// CDC 2-20 years: "Sex" (1 male, 2 female), "Agemos", median "M".
const cdcRows = readCsv("data/growth/cdc-weight-for-age-2-20y.csv");
const cdcFor = (sexCode) =>
  cdcRows.filter((row) => row.Sex === sexCode).map((row) => [Number(row.Agemos), Number(row.M)]);

// CDC recommends WHO standards below 24 months and CDC charts from 24 months.
const table = (whoLabel, cdcCode) => [
  ...whoRows(whoLabel).filter(([ageMonths]) => ageMonths < 24),
  ...cdcFor(cdcCode),
];

const format = (rows) => rows.map(([ageMonths, weightKg]) => `[${ageMonths}, ${weightKg}]`).join(",\n    ");

const output = `// GENERATED by scripts/build-growth-data.mjs from data/growth/*.csv. Do not edit.
//
// Median (50th percentile) body weight for age, in [age in months, weight in kg]
// pairs. Below 24 months: WHO Child Growth Standards; from 24 months: CDC 2000
// growth charts. Sources: whoWeightForAge, cdcWeightForAge in references.js.

export const MEDIAN_WEIGHT_FOR_AGE = {
  male: [
    ${format(table("boys", "1"))},
  ],
  female: [
    ${format(table("girls", "2"))},
  ],
};
`;
writeFileSync("src/growth-data.js", output);
console.log("wrote src/growth-data.js");
